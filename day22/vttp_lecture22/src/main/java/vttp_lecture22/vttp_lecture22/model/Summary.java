package vttp_lecture22.vttp_lecture22.model;

public class Summary {
    private Integer noBooks;
    private String author;
    private float avgStars;
    private float avgPrice;

    public Summary() {

    }

    public Integer getNoBooks() {
        return noBooks;
    }

    public void setNoBooks(Integer noBooks) {
        this.noBooks = noBooks;
    }

    public String getAuthor() {
        return author;
    }

    public void setAuthor(String author) {
        this.author = author;
    }

    public float getAvgStars() {
        return avgStars;
    }

    public void setAvgStars(float avgStars) {
        this.avgStars = avgStars;
    }

    public float getAvgPrice() {
        return avgPrice;
    }

    public void setAvgPrice(float avgPrice) {
        this.avgPrice = avgPrice;
    }
    

}
